#!/usr/bin/env python3
"""Bake the concept's curved light strips into a shared, flash-resident mask.

Coordinates are native 320x170 screen pixels. Each byte stores signed distance
to the nearest strip edge in eighth-pixel units, offset by eight pixels.
The renderer applies its current color, glow pulse and brightness with a small
palette. Both sides share this mask; the right side is mirrored.
"""
import argparse
import math
import re
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "light_mask.h"
HEADER = OUTPUT.parent / "include/ainekio/face.h"
LAYOUT_WIDTH = int(re.search(r"#define AINEKIO_FACE_LAYOUT_WIDTH (\d+)", HEADER.read_text())[1])
WIDTH_PERCENT = int(re.search(r"#define AINEKIO_FACE_WIDTH_PERCENT (\d+)", HEADER.read_text())[1])
ORIGIN_X, ORIGIN_Y, WIDTH, HEIGHT = -3, 24, 83, 113


def ribbon(points, start_width, end_width):
    # Narrow the placement/curve, while retaining the bright strip thickness.
    center = LAYOUT_WIDTH / 2
    points = [(center + (x * LAYOUT_WIDTH / 320 - center) * WIDTH_PERCENT / 100, y)
              for x, y in points]
    left, right = [], []
    for i in range(65):
        t = i / 64
        u = 1 - t
        x, y = (u**3 * points[0][axis] + 3*u*u*t * points[1][axis]
                + 3*u*t*t * points[2][axis] + t**3 * points[3][axis]
                for axis in (0, 1))
        dx, dy = (3*u*u * (points[1][axis]-points[0][axis])
                  + 6*u*t * (points[2][axis]-points[1][axis])
                  + 3*t*t * (points[3][axis]-points[2][axis])
                  for axis in (0, 1))
        radius = (start_width + (end_width-start_width)*t) / 2
        length = math.hypot(dx, dy)
        nx, ny = -dy/length*radius, dx/length*radius
        left.append((x+nx, y+ny))
        right.append((x-nx, y-ny))
    return left + right[::-1]


def distance(x, y, polygon):
    inside, nearest = False, float("inf")
    for (ax, ay), (bx, by) in zip(polygon, polygon[1:] + polygon[:1]):
        dx, dy = bx-ax, by-ay
        t = max(0, min(1, ((x-ax)*dx + (y-ay)*dy) / (dx*dx+dy*dy)))
        nearest = min(nearest, (x-ax-t*dx)**2 + (y-ay-t*dy)**2)
        if (ay > y) != (by > y) and x < ax + (y-ay)*dx/dy:
            inside = not inside
    return math.sqrt(nearest) * (-1 if inside else 1)


def generate():
    strips = [
        ribbon([(47, 48), (34, 75), (38, 99), (64, 115)], 8.5, 7.5),
        ribbon([(33, 44), (27, 54), (27, 65), (30, 73)], 3.2, 1.8),
    ]
    rows = []
    for y in range(ORIGIN_Y, ORIGIN_Y + HEIGHT):
        values = []
        for x in range(ORIGIN_X, ORIGIN_X + WIDTH):
            edge = min(distance(x, y, strip) for strip in strips)
            values.append(max(0, min(255, math.floor((edge+8)*8+.5))))
        rows.append("    " + ",".join(str(v) for v in values) + ",")
    return (
        "/* Generated by tools/bake_lights.py; edit the ribbon geometry there. */\n"
        "#pragma once\n#include <stdint.h>\n"
        f"enum {{ LIGHT_X={ORIGIN_X}, LIGHT_Y={ORIGIN_Y}, "
        f"LIGHT_WIDTH={WIDTH}, LIGHT_HEIGHT={HEIGHT} }};\n"
        "static const uint8_t light_mask[LIGHT_WIDTH*LIGHT_HEIGHT] = {\n"
        + "\n".join(rows) + "\n};\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit("light_mask.h differs from its geometry source")
        print("Light mask matches its geometry source")
    else:
        OUTPUT.write_text(generated)
        print(f"Baked one mirrored light mask: {WIDTH*HEIGHT} bytes")
