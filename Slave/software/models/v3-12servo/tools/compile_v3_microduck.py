"""Compile a trained V3 12-DOF neural gait ONNX policy into int8 C weights & binary payload.

Contract: ainekio-v3-neural-gait-v2-proprio (50 features x 12 frames = 600 obs -> 128 -> 64 -> 32 -> 12).
Outputs 12 normalized [-1, 1] Cartesian foot offsets [dx, dy, dz] per leg, scaled by action_scale_mm.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
from pathlib import Path

import numpy as np

SCHEMA = "ainekio-v3-neural-gait-v2-proprio"
OBS_SIZE = 600
H0, H1, H2, ACTIONS = 128, 64, 32, 12
MODEL_DIR = Path(__file__).resolve().parents[1]
OUT_DIR = MODEL_DIR / "motions" / "microduck"
DEFAULT_C = OUT_DIR / "v3_microduck_data.c"
DEFAULT_BIN = OUT_DIR / "policy.bin"
DEFAULT_MANIFEST = OUT_DIR / "manifest.json"


def _quantize_rows(mat: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    mat = np.asarray(mat, dtype=np.float32)
    scales = np.max(np.abs(mat), axis=1) / 127.0
    safe = np.where(scales > 1e-12, scales, 1.0)
    q = np.clip(np.rint(mat / safe[:, None]), -127, 127).astype(np.int8)
    scales = np.where(scales > 1e-12, scales, 0.0).astype(np.float32)
    return q, scales


def _fmt_floats(arr: np.ndarray, per_line: int = 12) -> str:
    vals = [f"{float(v):.9g}" for v in np.asarray(arr).ravel()]
    return ",\n".join(",".join(vals[i : i + per_line]) for i in range(0, len(vals), per_line))


def _fmt_i8_2d(mat: np.ndarray) -> str:
    rows = []
    for r in mat:
        rows.append("    {" + ",".join(str(int(v)) for v in r) + "}")
    return ",\n".join(rows)


def _extract_onnx(onnx_path: Path):
    import onnx
    from onnx import numpy_helper

    model = onnx.load(str(onnx_path))
    inits = {t.name: numpy_helper.to_array(t) for t in model.graph.initializer}

    obs_mean = np.zeros(OBS_SIZE, dtype=np.float32)
    obs_std = np.ones(OBS_SIZE, dtype=np.float32)
    gemms = []
    for node in model.graph.node:
        if node.op_type == "Sub":
            for inp in node.input:
                if inp in inits and inits[inp].size == OBS_SIZE:
                    obs_mean = inits[inp].reshape(OBS_SIZE).astype(np.float32)
        elif node.op_type == "Div":
            for inp in node.input:
                if inp in inits and inits[inp].size == OBS_SIZE:
                    obs_std = inits[inp].reshape(OBS_SIZE).astype(np.float32)
        elif node.op_type == "Gemm":
            w = inits[node.input[1]].astype(np.float32)
            b = inits[node.input[2]].astype(np.float32) if len(node.input) > 2 else np.zeros(w.shape[0], dtype=np.float32)
            trans_b = 0
            for attr in node.attribute:
                if attr.name == "transB":
                    trans_b = attr.i
            if trans_b == 0:
                w = w.T
            gemms.append((w, b.reshape(-1)))

    if len(gemms) != 4:
        raise ValueError(f"Expected 4 Gemm layers, found {len(gemms)}")
    expected = [(H0, OBS_SIZE), (H1, H0), (H2, H1), (ACTIONS, H2)]
    for idx, ((w, b), exp) in enumerate(zip(gemms, expected)):
        if w.shape != exp or b.shape != (exp[0],):
            raise ValueError(f"Layer {idx} shape mismatch: got W={w.shape} b={b.shape}, expected {exp}")
    return obs_mean, obs_std, gemms


def write_outputs(
    obs_mean: np.ndarray,
    obs_std: np.ndarray,
    gemms,
    *,
    trained: bool,
    action_scale_mm: tuple[float, float, float],
    source_sha: str,
) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    layers = []
    for w, b in gemms:
        q, sc = _quantize_rows(w)
        layers.append((q, sc, b.astype(np.float32)))

    # Binary payload
    buf = bytearray()
    buf += b"AV3P"
    buf += struct.pack("<HHHHB3x3f", OBS_SIZE, H0, H1, H2, 1 if trained else 0, *action_scale_mm)
    buf += obs_mean.astype("<f4").tobytes()
    buf += obs_std.astype("<f4").tobytes()
    for q, sc, b in layers:
        buf += q.tobytes()
        buf += sc.astype("<f4").tobytes()
        buf += b.astype("<f4").tobytes()
    DEFAULT_BIN.write_bytes(bytes(buf))
    bin_sha = hashlib.sha256(bytes(buf)).hexdigest()

    c_src = f"""/* Generated by tools/compile_v3_microduck.py. Do not edit by hand.
 * Source ONNX SHA-256: {source_sha}
 * Policy BIN SHA-256:  {bin_sha}
 */
#include "ainekio/v3_model.h"

const ainekio_v3_microduck_model_t ainekio_v3_microduck_default_model = {{
    .h0 = {H0}U,
    .h1 = {H1}U,
    .h2 = {H2}U,
    .trained = {'true' if trained else 'false'},
    .obs_mean = {{
{_fmt_floats(obs_mean)}
    }},
    .obs_std = {{
{_fmt_floats(obs_std)}
    }},
    .action_scale_mm = {{{action_scale_mm[0]:.9g}, {action_scale_mm[1]:.9g}, {action_scale_mm[2]:.9g}}},
    .weight0_q = {{
{_fmt_i8_2d(layers[0][0])}
    }},
    .scale0 = {{
{_fmt_floats(layers[0][1])}
    }},
    .bias0 = {{
{_fmt_floats(layers[0][2])}
    }},
    .weight1_q = {{
{_fmt_i8_2d(layers[1][0])}
    }},
    .scale1 = {{
{_fmt_floats(layers[1][1])}
    }},
    .bias1 = {{
{_fmt_floats(layers[1][2])}
    }},
    .weight2_q = {{
{_fmt_i8_2d(layers[2][0])}
    }},
    .scale2 = {{
{_fmt_floats(layers[2][1])}
    }},
    .bias2 = {{
{_fmt_floats(layers[2][2])}
    }},
    .weight3_q = {{
{_fmt_i8_2d(layers[3][0])}
    }},
    .scale3 = {{
{_fmt_floats(layers[3][1])}
    }},
    .bias3 = {{
{_fmt_floats(layers[3][2])}
    }},
}};
"""
    DEFAULT_C.write_text(c_src)
    DEFAULT_MANIFEST.write_text(
        json.dumps(
            {
                "model": "v3-12servo",
                "schema": SCHEMA,
                "trained": trained,
                "obs_size": OBS_SIZE,
                "hidden_dims": [H0, H1, H2],
                "actions": ACTIONS,
                "action_scale_mm": list(action_scale_mm),
                "source_onnx_sha256": source_sha,
                "policy_bin_sha256": bin_sha,
                "policy_bin_bytes": len(buf),
                "physical_qualified": False,
            },
            indent=2,
        )
        + "\n"
    )
    print(f"Generated {DEFAULT_C} (trained={trained}, bin={len(buf)} bytes)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--import-onnx", type=Path, default=None)
    ap.add_argument("--placeholder", action="store_true")
    ap.add_argument("--foot-scale-x-mm", type=float, default=78.0)
    ap.add_argument("--foot-scale-y-mm", type=float, default=28.0)
    ap.add_argument("--foot-scale-z-mm", type=float, default=36.0)
    args = ap.parse_args()
    scales = (args.foot_scale_x_mm, args.foot_scale_y_mm, args.foot_scale_z_mm)
    if args.placeholder or args.import_onnx is None:
        obs_mean = np.zeros(OBS_SIZE, dtype=np.float32)
        obs_std = np.ones(OBS_SIZE, dtype=np.float32)
        gemms = [
            (np.zeros((H0, OBS_SIZE), dtype=np.float32), np.zeros(H0, dtype=np.float32)),
            (np.zeros((H1, H0), dtype=np.float32), np.zeros(H1, dtype=np.float32)),
            (np.zeros((H2, H1), dtype=np.float32), np.zeros(H2, dtype=np.float32)),
            (np.zeros((ACTIONS, H2), dtype=np.float32), np.zeros(ACTIONS, dtype=np.float32)),
        ]
        write_outputs(obs_mean, obs_std, gemms, trained=False, action_scale_mm=scales, source_sha="placeholder")
    else:
        obs_mean, obs_std, gemms = _extract_onnx(args.import_onnx)
        sha = hashlib.sha256(args.import_onnx.read_bytes()).hexdigest()
        write_outputs(obs_mean, obs_std, gemms, trained=True, action_scale_mm=scales, source_sha=sha)


if __name__ == "__main__":
    main()
